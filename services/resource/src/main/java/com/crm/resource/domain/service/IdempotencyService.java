package com.crm.resource.domain.service;

import com.crm.resource.common.error.IdempotencyPayloadMismatchException;
import com.crm.resource.persistence.entity.IdempotencyRecord;
import com.crm.resource.persistence.repository.IdempotencyRecordRepository;
import org.springframework.beans.factory.annotation.Value;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.scheduling.annotation.Scheduled;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.Clock;
import java.time.Instant;
import java.time.temporal.ChronoUnit;
import java.util.UUID;

/**
 * Challenge 2 (BR2, BR3). Implements the decision table of functional-design.md 9.2 EXACTLY:
 * the PK insert of {@code (key, fingerprint, IN_PROGRESS)} is the concurrency guard — nothing
 * here reads before writing. Two simultaneous identical requests both attempt the insert;
 * PostgreSQL lets exactly one in. The loser's insert blocks on the uncommitted key until the
 * winner's transaction ends, then fails — by which point the record is COMPLETED, so the loser
 * replays the winner's exact response (AC-2.1, AC-2.3).
 *
 * <p>========================= BUILDING BLOCKS ALREADY CREATED =========================
 * <ul>
 *   <li>{@code repository} — IdempotencyRecordRepository (save/saveAndFlush/findById inherited
 *       from JpaRepository; {@code deleteExpired(Instant)} for the retention sweep — not needed
 *       in this method)
 *   <li>{@code savepointGuard} — SavepointGuard.insertOrRecover(Runnable insert,
 *       Supplier&lt;T&gt; onDuplicate) — implement SavepointGuard first (it is what makes the
 *       recovery read possible after the duplicate-key violation aborts the transaction)
 *   <li>IdempotencyRecord.inProgress(key, fingerprint, reservationId, now, expiresAt) — static
 *       factory already on the entity
 *   <li>new IdempotencyPayloadMismatchException(key) -&gt; 422, already built
 *   <li>{@code retentionHours} — injected from {@code idempotency.retention-hours}
 *       (IDEMPOTENCY_RETENTION_HOURS, default 24)
 * </ul>
 * ===================================================================================
 */
@Service
public class IdempotencyService {

    private static final Logger log = LoggerFactory.getLogger(IdempotencyService.class);
    private static final String STATE_COMPLETED = "COMPLETED";

    private final IdempotencyRecordRepository repository;
    private final Clock clock;
    private final long retentionHours;

    public IdempotencyService(IdempotencyRecordRepository repository, Clock clock,
                              @Value("${idempotency.retention-hours:24}") long retentionHours) {
        this.repository = repository;
        this.clock = clock;
        this.retentionHours = retentionHours;
    }

    /**
     * Steps 3-6 of the decision table. {@code candidateReservationId} is generated by the caller
     * BEFORE this call, precisely so an in-flight duplicate has a reservation to point at
     * (functional-design.md 9.2, step 6).
     *
     * <p>Suggested shape (functional-design.md 9.2's pseudocode is close to literal):
     * <ol>
     *   <li>{@code Instant now = clock.instant();}
     *   <li>call {@code SavepointGuard.insertOrRecover(...)}:
     *     <ul>
     *       <li>insert: {@code repository.saveAndFlush(IdempotencyRecord.inProgress(key,
     *           fingerprint, candidateReservationId, now, now.plus(retentionHours, ChronoUnit.HOURS)))}
     *       <li>onDuplicate: call a private {@code decideFromStoredRecord(key, fingerprint)}
     *           helper — reached only after the savepoint rollback restored the transaction
     *     </ul>
     *   <li>if the guard returned null (no duplicate) -&gt; {@code IdempotencyDecision.fresh()}
     *   <li>otherwise return what the guard returned
     * </ol>
     */
    public IdempotencyDecision beginOrReplay(String key, String fingerprint, UUID candidateReservationId) {
        // The primary-key insert IS the guard: nothing is read before writing. The database
        // decides who was first, and the affected-row count is that decision.
        //
        // expires_at = now + idempotency.retention-hours, read from config and never hard-coded,
        // so the record's own horizon and what the sweep deletes can never disagree (A13).
        Instant now = clock.instant();
        int inserted = repository.insertIfAbsent(key, fingerprint, candidateReservationId.toString(),
                now.plus(retentionHours, ChronoUnit.HOURS));

        if (inserted == 1) {
            return IdempotencyDecision.fresh();        // step 3: we are the first caller
        }
        // The key was already taken. Safe to read it: no statement failed, so this transaction
        // is healthy (see IdempotencyRecordRepository.insertIfAbsent for why that matters).
        return decideFromStoredRecord(key, fingerprint);
    }

    /**
     * Reached only on a duplicate key, after SavepointGuard's rollback has restored the
     * transaction. Fingerprint differs -&gt; 422 (step 4). Fingerprint matches + COMPLETED ->
     * replay (step 5). Fingerprint matches + IN_PROGRESS -&gt; inFlight (step 6).
     *
     * <p>Deliberately does NOT look at expires_at: expiry is enforced by deletion (the sweep),
     * not by comparison (functional-design.md 9.2, assumption A13).
     */
    private IdempotencyDecision decideFromStoredRecord(String key, String fingerprint) {
        IdempotencyRecord stored = repository.findById(key).orElseThrow();
        if (!stored.getRequestFingerprint().equals(fingerprint)) {
            throw new IdempotencyPayloadMismatchException(key);               // step 4 -> 422
        }
        if (STATE_COMPLETED.equals(stored.getState())) {
            log.info("idempotency.replay key={}", key);
            return IdempotencyDecision.replay(stored);                        // step 5
        }
        log.info("idempotency.in-flight key={} reservationId={}", key, stored.getReservationId());
        return IdempotencyDecision.inFlight(stored.getReservationId());       // step 6
    }

    /**
     * Step (d)/(b) of ProvisioningService.provision: freeze the final response on the key so
     * every replay is byte-identical (AC-2.1). Sets state=COMPLETED, response_status, response_body.
     */
    public void complete(String key, int responseStatus, String responseBody) {
        IdempotencyRecord record = repository.findById(key).orElseThrow();
        record.setState(STATE_COMPLETED);
        record.setResponseStatus(responseStatus);
        record.setResponseBody(responseBody);
        repository.save(record);
    }

    /**
     * Retention sweep (nfr-design.md 9, D5): deletes rows past their own expires_at, every
     * IDEMPOTENCY_SWEEP_INTERVAL_MS (default one hour). This is what actually makes a key
     * reusable again, so a key becomes reusable between retention-hours and retention-hours +
     * one sweep interval after first use (functional-design.md 9.2).
     */
    @Scheduled(fixedDelayString = "${idempotency.sweep-interval-ms:3600000}",
            initialDelayString = "${idempotency.sweep-interval-ms:3600000}")
    @Transactional
    public void sweepExpired() {
        int deleted = repository.deleteExpired(clock.instant());
        if (deleted > 0) {
            log.info("idempotency.sweep deleted={}", deleted);
        }
    }
}